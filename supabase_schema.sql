-- Run this in Supabase SQL Editor.
-- For a classroom demo, this permits anonymous survey inserts and public aggregate-row reads.
-- Do not collect names or sensitive personal information. Consider restricting reads to authorized users.

create table if not exists public.study_habits (
  id bigint generated by default as identity primary key,
  student_code text,
  study_hours numeric not null check (study_hours between 0 and 24),
  attendance numeric not null check (attendance between 0 and 100),
  revision integer not null check (revision between 1 and 5),
  study_days integer not null check (study_days between 0 and 7),
  study_method text not null,
  sleep_hours numeric not null check (sleep_hours between 0 and 24),
  practice integer not null check (practice between 1 and 5),
  phone_distraction integer not null check (phone_distraction between 1 and 5),
  entertainment_hours numeric not null check (entertainment_hours between 0 and 24),
  cgpa numeric not null check (cgpa between 0 and 10),
  created_at timestamptz not null default now()
);

alter table public.study_habits enable row level security;

-- Survey submission from the public website:
create policy "Allow anonymous survey submissions"
on public.study_habits for insert to anon
with check (true);

-- Read access is required for the shared dashboard to calculate summaries.
-- Use only for non-sensitive, consented classroom data. Otherwise remove this policy
-- and move analytics behind a trusted server or restricted authenticated access.
create policy "Allow anonymous survey reads"
on public.study_habits for select to anon
using (true);

grant usage on schema public to anon;
grant select, insert on public.study_habits to anon;
grant usage, select on sequence public.study_habits_id_seq to anon;
